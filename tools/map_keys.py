#!/usr/bin/env python3
"""
Interactive key mapper for the T1000LE keyboard Pico firmware.

Flash the firmware (even with the empty placeholder keymap), connect the Pico
over USB, then run:

    pip install pyserial
    python3 tools/map_keys.py /dev/cu.usbmodemXXXX      # macOS
    python3 tools/map_keys.py /dev/ttyACM0              # Linux

For each key name it asks you to press that key on the T1000 keyboard and
records which KBSC/KBRTN pair it is. Press Enter on the computer to skip a key
the keyboard doesn't have, or type 'b' + Enter to go back one key.
At the end it writes keyboard/src/keymap.h. Rebuild and flash.
"""
import os
import re
import select
import sys

try:
    import serial
except ImportError:
    sys.exit("pyserial is required: pip install pyserial")

N_SCAN, N_RTN = 11, 8
OUT = os.path.join(os.path.dirname(__file__), "..", "keyboard", "src", "keymap.h")

# (label shown to you, HID constant). Order roughly follows the keyboard rows.
KEYS = [
    ("Esc", "HID_KEY_ESCAPE"),
    *[(f"F{i}", f"HID_KEY_F{i}") for i in range(1, 13)],
    ("Num Lock", "HID_KEY_NUM_LOCK"),
    ("Scroll Lock", "HID_KEY_SCROLL_LOCK"),
    ("Prt Sc / SysReq", "HID_KEY_PRINT_SCREEN"),
    ("Pause / Break", "HID_KEY_PAUSE"),
    ("` ~", "HID_KEY_GRAVE"),
    *[(c, f"HID_KEY_{c}") for c in "1234567890"],
    ("- _", "HID_KEY_MINUS"),
    ("= +", "HID_KEY_EQUAL"),
    ("Backspace", "HID_KEY_BACKSPACE"),
    ("Tab", "HID_KEY_TAB"),
    *[(c, f"HID_KEY_{c}") for c in "QWERTYUIOP"],
    ("[ {", "HID_KEY_BRACKET_LEFT"),
    ("] }", "HID_KEY_BRACKET_RIGHT"),
    ("\\ |", "HID_KEY_BACKSLASH"),
    ("Ctrl", "HID_KEY_CONTROL_LEFT"),
    ("Caps Lock", "HID_KEY_CAPS_LOCK"),
    *[(c, f"HID_KEY_{c}") for c in "ASDFGHJKL"],
    ("; :", "HID_KEY_SEMICOLON"),
    ("' \"", "HID_KEY_APOSTROPHE"),
    ("Enter", "HID_KEY_ENTER"),
    ("Left Shift", "HID_KEY_SHIFT_LEFT"),
    *[(c, f"HID_KEY_{c}") for c in "ZXCVBNM"],
    (", <", "HID_KEY_COMMA"),
    (". >", "HID_KEY_PERIOD"),
    ("/ ?", "HID_KEY_SLASH"),
    ("Right Shift", "HID_KEY_SHIFT_RIGHT"),
    ("Fn", "KC_FN"),
    ("Alt", "HID_KEY_ALT_LEFT"),
    ("Space", "HID_KEY_SPACE"),
    ("Right Alt (if any)", "HID_KEY_ALT_RIGHT"),
    ("Right Ctrl (if any)", "HID_KEY_CONTROL_RIGHT"),
    ("Ins", "HID_KEY_INSERT"),
    ("Del", "HID_KEY_DELETE"),
    ("Home", "HID_KEY_HOME"),
    ("End", "HID_KEY_END"),
    ("Pg Up", "HID_KEY_PAGE_UP"),
    ("Pg Dn", "HID_KEY_PAGE_DOWN"),
    ("Up", "HID_KEY_ARROW_UP"),
    ("Down", "HID_KEY_ARROW_DOWN"),
    ("Left", "HID_KEY_ARROW_LEFT"),
    ("Right", "HID_KEY_ARROW_RIGHT"),
]

EVENT = re.compile(rb"down SC(\d+) RTN(\d+)")


def wait_key(port):
    """Return (sc, rtn), None to skip, or 'back'."""
    buf = b""
    while True:
        r, _, _ = select.select([port.fileno(), sys.stdin], [], [])
        if sys.stdin in r:
            line = sys.stdin.readline().strip().lower()
            return "back" if line == "b" else None
        buf += port.read(port.in_waiting or 1)
        m = EVENT.search(buf)
        if m:
            return int(m.group(1)), int(m.group(2))


def write_keymap(assigned):
    base = [["KC_NO"] * N_RTN for _ in range(N_SCAN)]
    for (sc, rtn), (_, code) in assigned.items():
        base[sc][rtn] = code

    def table(rows):
        return "\n".join("        {" + ", ".join(r) + "}," for r in rows)

    trns = [["KC_TRNS"] * N_RTN for _ in range(N_SCAN)]
    legend = "\n".join(
        f" *   SC{sc:<2} RTN{rtn}: {label}" for (sc, rtn), (label, _) in sorted(assigned.items())
    )
    with open(OUT, "w") as f:
        f.write(
            f"""/*
 * Generated by tools/map_keys.py.
 * keymap[layer][KBSC][KBRTN]; layer 1 is active while Fn is held.
 * Edit layer 1 by hand for Fn combos, e.g. Fn+Up -> HID_KEY_PAGE_UP.
 *
{legend}
 */
#include "keycodes.h"

static const uint8_t keymap[2][11][8] = {{
    [0] = {{
{table(base)}
    }},
    [1] = {{
{table(trns)}
    }},
}};
"""
        )
    print(f"\nWrote {os.path.normpath(OUT)} ({len(assigned)} keys). Rebuild and flash the Pico.")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    port = serial.Serial(sys.argv[1], 115200, timeout=0)
    print("Press each key on the T1000 keyboard when asked.")
    print("Enter here = key doesn't exist (skip), 'b' + Enter = go back.\n")
    assigned = {}  # (sc, rtn) -> (label, code)
    i = 0
    while i < len(KEYS):
        label, code = KEYS[i]
        print(f"[{i + 1}/{len(KEYS)}] Press: {label} ... ", end="", flush=True)
        port.reset_input_buffer()
        res = wait_key(port)
        if res == "back":
            i = max(0, i - 1)
            prev = KEYS[i][1]
            assigned = {k: v for k, v in assigned.items() if v[1] != prev}
            print("back")
            continue
        if res is None:
            print("skipped")
            i += 1
            continue
        if res in assigned:
            print(f"SC{res[0]} RTN{res[1]} is already '{assigned[res][0]}', try again")
            continue
        assigned[res] = (label, code)
        print(f"SC{res[0]} RTN{res[1]}")
        i += 1
    write_keymap(assigned)


if __name__ == "__main__":
    main()
